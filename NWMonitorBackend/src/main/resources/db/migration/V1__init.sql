CREATE TABLE users (
    id UUID PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    display_name VARCHAR(128) NOT NULL,
    email VARCHAR(255),
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL,
    -- 'ROOT' for the single root user, NULL for everyone else; UNIQUE guarantees at most one root
    root_marker VARCHAR(4) UNIQUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    failed_logins INT NOT NULL DEFAULT 0,
    locked_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE refresh_tokens (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE devices (
    id UUID PRIMARY KEY,
    mac VARCHAR(17) NOT NULL UNIQUE,
    ip VARCHAR(45),
    hostname VARCHAR(255),
    vendor VARCHAR(128),
    label VARCHAR(128),
    device_type VARCHAR(16) NOT NULL,
    parent_id UUID REFERENCES devices(id) ON DELETE SET NULL,
    status VARCHAR(8) NOT NULL,
    trusted BOOLEAN NOT NULL DEFAULT FALSE,
    randomized_mac BOOLEAN NOT NULL DEFAULT FALSE,
    first_seen TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_devices_ip ON devices(ip);

CREATE TABLE daily_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    usage_date DATE NOT NULL,
    bytes_down BIGINT NOT NULL DEFAULT 0,
    bytes_up BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_usage_device_day UNIQUE (device_id, usage_date)
);
CREATE INDEX idx_usage_date ON daily_usage(usage_date);

CREATE TABLE web_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    domain VARCHAR(255) NOT NULL,
    queried_at TIMESTAMP WITH TIME ZONE NOT NULL,
    blocked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_activity_device_time ON web_activity(device_id, queried_at);
CREATE INDEX idx_activity_time ON web_activity(queried_at);

CREATE TABLE alerts (
    id UUID PRIMARY KEY,
    type VARCHAR(32) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(2000),
    device_id UUID REFERENCES devices(id) ON DELETE SET NULL,
    source_ip VARCHAR(45),
    dedupe_key VARCHAR(255),
    occurrences INT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_by VARCHAR(64),
    acknowledged_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_alerts_status_time ON alerts(status, created_at);
CREATE INDEX idx_alerts_dedupe ON alerts(dedupe_key);

CREATE TABLE app_settings (
    setting_key VARCHAR(64) PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
